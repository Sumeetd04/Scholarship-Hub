def seed_all(conn: sqlite3.Connection) -> None:
    # Admin + demo users ------------------------------------------------------
    conn.execute(
        """INSERT INTO users (full_name, email, phone, password_hash, role, otr, dob, gender,
                              category, annual_income, state, institute, course, level)
           VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?)""",
        (
            "Portal Administrator", config.ADMIN_EMAIL, "+91 80000 00001",
            hash_password(config.ADMIN_PASSWORD), "admin", "OTR-ADMIN-2026",
            "1988-06-01", "Other", "General", 0, "Maharashtra",
            "Scholarship Hub", "Portal operations", "Multiple Levels",
        ),
    )

    # Scholarships -----------------------------------------------------------
    cols = [
        "slug", "name", "provider", "category", "level", "state", "amount", "amount_value",
        "deadline", "description", "eligibility", "benefits", "documents", "apply_mode",
        "official_link", "tags", "income_limit", "gender", "minority", "disability",
        "awards", "featured", "status",
    ]
    placeholders = ",".join("?" for _ in cols)
    conn.executemany(
        f"INSERT INTO scholarships ({','.join(cols)}) VALUES ({placeholders})",
        [tuple(item.get(c, "") for c in cols) for item in SCHOLARSHIPS],
    )

    # Announcements ----------------------------------------------------------
    conn.executemany(
        "INSERT INTO announcements (title, body, tag, pinned, link) VALUES (?,?,?,?,?)",
        [(a["title"], a["body"], a["tag"], a["pinned"], a["link"]) for a in ANNOUNCEMENTS],
    )

    # Demo student data ------------------------------------------------------
    _seed_scorecard(conn)

    # Refresh any deadlines that have drifted into the past so the demo
    # catalogue always looks live. Keeps the same month/day, moves year forward.
    today = datetime.now(timezone.utc).date()
    for row in conn.execute("SELECT id, deadline FROM scholarships").fetchall():
        try:
            year, month, day = (int(p) for p in row["deadline"].split("-"))
        except ValueError:
            continue
        deadline = datetime(year, month, day).date()
        if deadline < today:
            try:
                deadline = deadline.replace(year=deadline.year + 1)
            except ValueError:
                deadline = deadline.replace(year=deadline.year + 1, day=28)
            conn.execute("UPDATE scholarships SET deadline = ? WHERE id = ?",
                         (deadline.isoformat(), row["id"]))
